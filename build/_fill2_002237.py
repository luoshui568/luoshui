def purge_missing(d, log):
    """清理已补齐后残留的 [MISSING] 段落 —— 但保留 KEEP_MISSING 里真实的外部缺口。"""
    removed = 0
    for k, v in d.items():
        if not isinstance(v, dict):
            continue
        dl = v.get('deep')
        if not isinstance(dl, list):
            continue
        keep = []
        for it in dl:
            s = json.dumps(it, ensure_ascii=False)
            if '[MISSING]' in s and not any(km in s for km in KEEP_MISSING):
                removed += 1
                continue
            keep.append(it)
        v['deep'] = keep
    log.append('已清理 %d 段已补齐的 [MISSING] 段落' % removed)


def _scrub(obj):
    """递归清除 source/note 字符串里残留的 [MISSING] 令牌（KEEP_MISSING 除外）。"""
    n = 0
    if isinstance(obj, dict):
        for k, v in list(obj.items()):
            if isinstance(v, str) and '[MISSING]' in v and not any(km in v for km in KEEP_MISSING):
                obj[k] = v.replace('[MISSING]', '').strip()
                n += 1
            else:
                n += _scrub(v)
    elif isinstance(obj, list):
        for it in obj:
            n += _scrub(it)
    return n


