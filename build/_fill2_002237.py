def deep_list(d, key):
    """取得（必要时建立）某块的 deep 数组。"""
    blk = d.get(key)
    if not isinstance(blk, dict):
        blk = {}
        d[key] = blk
    return blk.setdefault('deep', [])


def has_deep(d, key, marker):
    """幂等判据：该块 deep 里是否已有含 marker 的段/表。"""
    for it in (deep_list(d, key)):
        if not isinstance(it, dict):
            continue
        blob = json.dumps(it, ensure_ascii=False)
        if marker in blob:
            return True
    return False


