def has_id(d, key, marker):
    """幂等判据：该块 deep 里是否已有含 marker 的条目。

    ⚠️ 只匹配 **k（小标题）与 h3/h4 的 x（标题文本）**，不匹配整个 JSON blob。
       原因：blob 里含转义引号与换行，子串匹配容易被 `）`、`」` 这类全角标点截断，
       造成「明明写了却判为没有」→ 重复插入 → 幂等失败（本脚本已踩过两次）。
    """
    v = d.get(key)
    if not isinstance(v, dict):
        return False
    for it in (v.get('deep') or []):
        if not isinstance(it, dict):
            continue
        for f in ('k',):                      # logic 块的小标题
            if marker in str(it.get(f) or ''):
                return True
        if (it.get('t') or '').lower() in ('h3', 'h4') and marker in str(it.get('x') or ''):
            return True
    return False


def hunt_none(obj, path='$'):
    """铁律：任何 deep 段里不允许出现 None 值（会渲染成 'None' 字面量）。"""
    bad = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            bad += hunt_none(v, path + '.' + str(k))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            bad += hunt_none(v, path + '[%d]' % i)
    elif obj is None:
        bad.append(path)
    return bad


