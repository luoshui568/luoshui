def check_common(code, data, new_mods, new_charts, seed):
    errs = []
    # ① 编号 1..31
    nos = sorted(int(m['no']) for m in seed['mods'])
    if nos != list(range(1, 32)):
        errs.append('seed 编号不是 1..31')
    # ② 未采纳的槽必须是「重渲染更短」，且必须打印出来（不静默）
    for no in RENDER_SLOTS:
        if str(no) in new_mods:
            continue
        h = B.RENDER[no](data)
        h_old = {str(m['no']): (m.get('html') or '') for m in seed['mods']}[str(no)]
        if h != h_old and len(h) >= len(h_old):
            errs.append('槽 %d 本应被替换却没换' % no)
    # ③ 新增图必须被 html 引用；html 不得引用不存在的图槽
    ids = {c['id'] for c in (seed.get('charts') or [])} | set(new_charts)
    used = set()
    for m in seed['mods']:
        h = new_mods.get(str(m['no']), m.get('html') or '')
        used |= set(re.findall(r'data-chart="([^"]+)"', h))
    if set(new_charts) - used:
        errs.append('新增图未被任何模块引用：%s' % sorted(set(new_charts) - used))
    ghost = used - ids
    if ghost:
        errs.append('html 引用了不存在的图槽：%s' % sorted(ghost))
    # ④ 不许出现 None
    def hunt(o, p=''):
        bad = []
        if isinstance(o, dict):
            for k, v in o.items():
                bad += hunt(v, '%s.%s' % (p, k) if p else str(k))
        elif isinstance(o, list):
            for i, v in enumerate(o):
                bad += hunt(v, '%s[%d]' % (p, i))
        elif o is None:
            bad.append(p)
        return bad
    ns = hunt(data)
    if ns:
        errs.append('data_v31 里出现 %d 处 None（应改用空串留白）：%s'
                    % (len(ns), ', '.join(ns[:8])))
    # ⑤ 幂等
    d2 = apply_pack(code, PACKS[code])
    if json.dumps(d2, ensure_ascii=False, sort_keys=True) != \
            json.dumps(data, ensure_ascii=False, sort_keys=True):
        errs.append('apply_pack 非幂等')
    return errs


