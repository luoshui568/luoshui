def md5(p):
    return hashlib.md5(io.open(p, 'rb').read()).hexdigest()


def merge(dst, src):
    """浅合并：dict 递归合并，其余（list/标量）直接替换。"""
    for k, v in src.items():
        if isinstance(v, dict) and isinstance(dst.get(k), dict):
            merge(dst[k], v)
        else:
            dst[k] = v


def load_flow(code):
    """读 data_v31_<code>_flow.json（timeline / equity_tree 等视觉件数据）。

    ★ 独立成文件而不是塞进 pack：flow 与 pack 是两种数据，前者喂 chartflow.py
    （时间轴 / 股权树），后者喂 report_build_v31 的表格渲染器。缺文件时返回 {}，
    让 m2/m3 自己回落（不静默造数据）。
    """
    fp = os.path.join(SEED, 'data_v31_%s_flow.json' % code)
    if not os.path.exists(fp):
        return {}
    d = json.load(io.open(fp, encoding='utf-8'))
    d.pop('_说明', None)
    return d


def apply_pack(code, pack):
    """把 pack（+ flow 文件）合并进 data_v31_<code>.json（不落盘）。"""
    dp = os.path.join(SEED, 'data_v31_%s.json' % code)
    d = json.load(io.open(dp, encoding='utf-8'))
    flow = load_flow(code)
    before = json.dumps(d, ensure_ascii=False, sort_keys=True)
    merge(d, flow)
    merge(d, pack['data'])
    d.setdefault('chartNames', {}).update(pack.get('chartNames') or {})
    # 幂等：同样的 pack 应用两遍结果必须一致
    d2 = json.loads(before)
    merge(d2, flow)
    merge(d2, pack['data'])
    d2.setdefault('chartNames', {}).update(pack.get('chartNames') or {})
    assert json.dumps(d, ensure_ascii=False, sort_keys=True) == \
        json.dumps(d2, ensure_ascii=False, sort_keys=True), '%s pack 非幂等' % code
    return d


def find_table_after(h, title):
    """找出标题 `title` 之后的第一个 <table>…</table>，返回 (start, end, tag_attrs, block)。"""
    i = h.find(title)
    assert i >= 0, '找不到标题：%s' % title
    j = h.find('<table', i)
    assert j > i, '标题之后没有 <table>：%s' % title
    k = h.find('</table>', j)
    assert k > j, 'table 未闭合：%s' % title
    m = re.match(r'<table([^>]*)>', h[j:k])
    return j, k + len('</table>'), (m.group(1) if m else ''), h[j:k + len('</table>')]


def fill_dividend(h, rows, head_tail):
    """槽 16 手术：保留表头与其它内容，只重写「历年分红明细」的 5 行数据。

    ★★ 必须幂等 —— 说明段是**追加**的，重跑一次就会重复追加一遍。
       2026-09-21 实测踩坑：第二次运行时槽 16 从 3,336 涨到 5,190（多了一整段说明），
       表面看像「内容变厚了」，其实是脏数据。所以开头的「撤掉上轮追加」不能省。
    """
    if head_tail and head_tail in h:
        h = h.replace(head_tail, '', 1)          # ← 幂等的关键：先撤回上一次的追加
    j, k, attrs, blk = find_table_after(h, '<h3>历年分红明细</h3>')
    trs = re.findall(r'<tr[^>]*>.*?</tr>', blk, re.S)
    assert len(trs) == len(rows) + 1, \
        '分红明细表行数应为 %d+1，实际 %d —— 结构变了，停手' % (len(rows), len(trs))
    head = trs[0]
    ths = [re.sub(r'\s+', '', re.sub(r'<[^>]+>', '', x)) for x in
           re.findall(r'<th[^>]*>(.*?)</th>', head, re.S)]
    assert ths == ['年份', '每股股利', '每股收益', '分红率', '当期股息率'], \
        '分红明细表头变了：%s' % ths
    body = '\n'.join('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>' for r in rows)
    newblk = '<table%s>\n%s\n%s\n</table>' % (attrs, head, body)
    return h[:j] + newblk + head_tail + h[k:]


