def md5(p):
    return hashlib.md5(io.open(p, 'rb').read()).hexdigest()


def compute(code, res, sb):
    """算两槽 html + 三个图（不碰磁盘）。幂等：同样输入必得同样输出。"""
    data_p = os.path.join(SEED, 'data_v31_%s.json' % code)
    data = json.load(io.open(data_p, encoding='utf-8'))
    data['resource'] = res
    data['sdbalance'] = sb
    h25, h26 = B.m_res(data), B.m_sdbalance(data)
    opts = B.res_sd_charts(data)
    names = {
        'chartResDist': res.get('chart_name') or B.CHART_NAMES['chartResDist'],
        'chartResPrice': res.get('price_chart_name') or B.CHART_NAMES['chartResPrice'],
        'chartSDBalance': sb.get('chart_name') or B.CHART_NAMES['chartSDBalance'],
    }
    return data, h25, h26, opts, names


def check(code, res, sb):
    seed_p = os.path.join(SEED, 'report_%s.json' % code)
    seed = json.load(io.open(seed_p, encoding='utf-8'))
    data, h25, h26, opts, names = compute(code, res, sb)

    errs = []
    # ① 不留 [MISSING]
    for tag, h in (('25', h25), ('26', h26)):
        if MISS in h:
            errs.append('槽 %s 仍有 %s（%d 处）' % (tag, MISS, h.count(MISS)))
    # ② 图槽集合一致
    if sorted(opts) != sorted(NEW_IDS):
        errs.append('生成的图不对：%s' % sorted(opts))
    import re
    used = set(re.findall(r'data-chart="([^"]+)"', h25 + h26))
    if used != set(NEW_IDS):
        errs.append('html 引用的图槽 %s != 预期 %s' % (sorted(used), NEW_IDS))

    # ③ 其余 29 槽一字未动；④ 编号/标题
    old = {str(m['no']): m for m in seed['mods']}
    if sorted(int(k) for k in old) != list(range(1, 32)):
        errs.append('原 seed 编号不是 1..31')

    # ⑤ 幂等
    _, h25b, h26b, _o, _n = compute(code, res, sb)
    if (h25, h26) != (h25b, h26b):
        errs.append('非幂等：两次计算结果不同')

    new_mods = []
    for m in seed['mods']:
        no = str(m['no'])
        if no in ('25', '26'):
            new_mods.append(dict(m, html=(h25 if no == '25' else h26)))
        else:
            new_mods.append(m)
    changed = [str(m['no']) for a, m in zip(seed['mods'], new_mods) if a['html'] != m['html']]
    if changed != ['25', '26']:
        errs.append('被改动的槽不是恰好 25/26：%s' % changed)

    old_charts = [c for c in seed['charts'] if c['id'] not in NEW_IDS]
    charts = list(old_charts)
    for cid in NEW_IDS:
        charts.append({'seq': len(charts) + 1, 'id': cid, 'name': names[cid], 'opt': opts[cid]})
