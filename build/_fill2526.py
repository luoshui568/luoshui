    #    但槽 11 现在用的是 chartMargin。本次任务是**补 25/26 两槽**，不负责清理它
    #    （清理要动线上库，属另一件事）。
    #    ⇒ 因此这里只卡两件真正会坏版面的事：
    #       ① 本轮**新增的三张图**必须都被 html 引用（否则页面上少图）；
    #       ② html 不得引用不存在的图槽（否则图上永远加载不出来）。
    ids = {c['id'] for c in charts}
    allused = set()
    for m in new_mods:
        allused |= set(re.findall(r'data-chart="([^"]+)"', m['html']))
    missing_ref = set(NEW_IDS) - allused
    ghost = allused - ids
    if missing_ref or ghost:
        errs.append('图槽引用异常：本轮新增图未被引用 %s / html 引用了不存在的图 %s'
                    % (sorted(missing_ref), sorted(ghost)))
    orphan = sorted(ids - allused)
    if orphan:
        print('  ⓘ 既有孤儿图（不影响渲染，本脚本不动）：%s' % orphan)

    return errs, dict(seed, mods=new_mods, charts=charts, data=data,
                      _fill2526={'at': int(time.time() * 1000), 'slots': [25, 26],
                                 'charts': NEW_IDS})


