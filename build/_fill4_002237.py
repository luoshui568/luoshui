def build(d):
    d = json.loads(json.dumps(d))          # 深拷贝：幂等自检要比较两次结果
    d['resource'] = RESOURCE
    d['sdbalance'] = SDBALANCE
    # 企业评分留空 —— 撤掉逐项覆写，回到渲染器默认（⑦⑧⑩ 标 [MISSING]、不计入分母）
    sc = d.get('score')
    if isinstance(sc, dict):
        for k in ('items', 'order'):
            sc.pop(k, None)
        if not sc:
            d.pop('score', None)
    return d


def main():
    out = build(D)
    print('=== 将写入 ===')
    print('  resource  rows %d 行 · price_rows %d 行'
          % (len(RESOURCE['rows']), len(RESOURCE['price_rows'])))
    print('  sdbalance supply %d 行 · demand %d 行 · bal %d 行'
          % (len(SDBALANCE['supply_rows']), len(SDBALANCE['demand_rows']),
             len(SDBALANCE['bal_rows'])))
    print('  score     -> %s' % ('已移除（评分留空）' if 'score' not in out
                                 else sorted(out['score'].keys())))

    print()
    print('=== 自检 ===')
    # ① 幂等
    assert build(build(out)) == build(out), '幂等自检失败'
    print('  ① 幂等 build(build(x))==build(x)  ✅')
    # ② 图表列可解析（numcol 口径：浮点可转）
    for r in RESOURCE['rows']:
        float(str(r[1]).replace(',', '')), float(str(r[3]).replace(',', ''))
    for r in RESOURCE['price_rows']:
        float(r[1])
    for r in SDBALANCE['bal_rows']:
        float(r[1]), float(r[2])
    print('  ② 图表列均为可转浮点的数值  ✅')
    # ③ 行宽一致（表格渲染不串列）
    assert len({len(r) for r in RESOURCE['rows']}) == 1, 'resource.rows 列数不一致'
    assert len({len(r) for r in SDBALANCE['supply_rows']}) == 1, 'supply_rows 列数不一致'
    assert len({len(r) for r in SDBALANCE['demand_rows']}) == 1, 'demand_rows 列数不一致'
    assert len({len(r) for r in SDBALANCE['bal_rows']}) == 1, 'bal_rows 列数不一致'
    print('  ③ 每张表行宽一致  ✅')
    # ④ 占比合计
    tot_res = sum(r[1] for r in RESOURCE['rows'][:-1])
    print('  ④ 储量分项合计 %d 吨（USGS 公布全球合计 66,000，差额为四舍五入）' % tot_res)

    if not GO:
        print()
        print('（干跑结束，加 --go 才写文件）')
        return
    io.open(P, 'w', encoding='utf-8').write(json.dumps(out, ensure_ascii=False, indent=1))
    print()
    print('已写入 %s' % P)


if __name__ == '__main__':
    main()
