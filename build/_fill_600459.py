# 铁律：不许出现 None（None 会渲染成 [MISSING]，但空串是「有意留白」）
def hunt_none(o, path=''):
    bad = []
    if isinstance(o, dict):
        for k, v in o.items():
            bad += hunt_none(v, '%s.%s' % (path, k) if path else str(k))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            bad += hunt_none(v, '%s[%d]' % (path, i))
    elif o is None:
        bad.append(path)
    return bad
