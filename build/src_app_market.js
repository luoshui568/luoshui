/* ---- 术语悬停提示 ---- */
(function(){
  const tip = document.getElementById('tip');
  let cur = null;
  const place = e=>{
    if(!cur) return;
    const r = cur.getBoundingClientRect();
    let x = r.left + r.width/2 - 165;
    x = Math.max(10, Math.min(x, innerWidth - 350));
    let y = r.bottom + 10;
    if (y + 160 > innerHeight) y = r.top - 150;
    tip.style.left = x + 'px';
    tip.style.top = Math.max(10, y) + 'px';
  };
  document.addEventListener('mouseover', e=>{
    const t = e.target.closest('.term');
    if(!t) return;
    cur = t;
    tip.innerHTML = '<b>' + t.dataset.tipTitle + '</b>' + t.dataset.tip;
    tip.classList.add('on');
    place(e);
  });
  document.addEventListener('mouseout', e=>{
    if(e.target.closest('.term')) { tip.classList.remove('on'); cur=null; }
  });
  document.addEventListener('scroll', ()=>{ tip.classList.remove('on'); }, {passive:true});
})();

