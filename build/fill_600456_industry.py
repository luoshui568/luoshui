    old = d.get(key) or {}
    print()
    print('### %s' % key)
    for f in ('overview', 'cagr', 'rows', 'drivers', 'note', 'source'):
        o, n = old.get(f), new.get(f)
        if n is None:
            continue
        if o == n:
            print('  · %-9s 无变化' % f)
            continue
        print('  · %-9s 旧 %d 字符 → 新 %d 字符' % (f, len(o) if o is not None else 0, len(n)))
